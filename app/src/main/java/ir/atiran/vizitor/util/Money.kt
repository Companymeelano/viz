package ir.atiran.vizitor.util

import kotlin.math.roundToLong

/** مبلغ یک سطر فاکتور (ریال) — تعداد × فی با گرد کردن درست. */
fun lineAmount(quantity: Double, unitPrice: Long): Long =
    (quantity * unitPrice.toDouble()).roundToLong()
